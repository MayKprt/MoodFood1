import { test, expect } from "@playwright/test";

test("completed orders require confirmation, reopen once, persist, and complete again", async ({ page }) => {
  await page.goto("/merchant");
  await page.getByRole("navigation", { name: "Merchant navigation" }).getByRole("button", { name: /^Orders/ }).click();
  const tabs = page.getByRole("group", { name: "Order categories" });
  const count = async (name: string) => Number((await tabs.getByRole("button", { name: new RegExp(`^${name}`) }).innerText()).match(/\d+/)![0]);
  const initialActive = await count("In Progress");
  const initialCompleted = await count("Completed");
  await tabs.getByRole("button", { name: /^In Progress/ }).click();
  const ready = page.getByRole("article").filter({ has: page.getByRole("button", { name: "Complete Order", exact: true }) }).first();
  const heading = await ready.getByRole("heading").innerText();
  await ready.getByRole("button", { name: "Complete Order", exact: true }).click();
  expect(await count("Completed")).toBe(initialCompleted + 1);
  expect(await count("In Progress")).toBe(initialActive - 1);
  await tabs.getByRole("button", { name: /^Completed/ }).click();
  const order = page.getByRole("article").filter({ has: page.getByRole("heading", { name: heading, exact: true }) });
  await order.getByRole("button", { name: "Reopen Order", exact: true }).click();
  const dialog = page.getByRole("dialog");
  await expect(dialog.getByText("Move this order back to In Progress?", { exact: true })).toBeVisible();
  await dialog.getByRole("button", { name: "Cancel", exact: true }).click();
  await expect(dialog).not.toBeVisible();
  expect(await count("Completed")).toBe(initialCompleted + 1);
  await expect(order.getByRole("button", { name: "Reopen Order", exact: true })).toBeFocused();
  await order.getByRole("button", { name: "Reopen Order", exact: true }).click();
  await dialog.getByRole("button", { name: "Reopen Order", exact: true }).click();
  await expect(tabs.getByRole("button", { name: /^In Progress/ })).toHaveAttribute("aria-pressed", "true");
  await expect(tabs.getByRole("button", { name: /^In Progress/ })).toBeFocused();
  expect(await count("Completed")).toBe(initialCompleted);
  expect(await count("In Progress")).toBe(initialActive);
  await expect(order).toHaveCount(1);
  await expect(order.getByRole("button", { name: "Complete Order", exact: true })).toBeEnabled();
  await page.reload();
  await page.getByRole("navigation", { name: "Merchant navigation" }).getByRole("button", { name: /^Orders/ }).click();
  await tabs.getByRole("button", { name: /^In Progress/ }).click();
  await expect(order).toHaveCount(1);
  await order.getByRole("button", { name: "Complete Order", exact: true }).click();
  expect(await count("Completed")).toBe(initialCompleted + 1);
  expect(await count("In Progress")).toBe(initialActive - 1);
});
